// Regenerates src/styles/fonts.css from @fontsource (cyrillic + latin, WOFF2 only, the 6 app weights).
// Own @font-face (instead of importing fontsource CSS) so no legacy .woff files end up in dist/.
import { readFileSync, writeFileSync } from "node:fs";

const FONTS = [
  ["comfortaa", "Comfortaa", [600, 700]],
  ["nunito", "Nunito", [400, 600, 700, 800]],
];
const SUBSETS = ["cyrillic", "latin"];
let out = "/* GENERATED by scripts/generate-fonts-css.mjs — do not edit. Self-hosted, font-display: swap. */\n";
for (const [pkg, family, weights] of FONTS) {
  for (const w of weights) {
    const css = readFileSync(`node_modules/@fontsource/${pkg}/${w}.css`, "utf8");
    for (const s of SUBSETS) {
      const m = css.match(new RegExp(`/\\* ${pkg}-${s}-${w}-normal \\*/[\\s\\S]*?unicode-range: ([^;]+);`));
      if (!m) throw new Error(`no unicode-range for ${pkg} ${s} ${w}`);
      out += `@font-face {
  font-family: "${family}";
  font-style: normal;
  font-display: swap;
  font-weight: ${w};
  src: url("../../node_modules/@fontsource/${pkg}/files/${pkg}-${s}-${w}-normal.woff2") format("woff2");
  unicode-range: ${m[1]};
}
`;
    }
  }
}
writeFileSync("src/styles/fonts.css", out);
console.log("fonts.css written");
